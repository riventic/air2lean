#!/usr/bin/env python3
"""Measured peak memory of each Lean module's elaboration, for build-guard's per-process charge.

    python3 -B scripts/lean-peaks.py write [--lock LOCK]   regenerate assurance/lean-peaks.json
    python3 -B scripts/lean-peaks.py top [N] [--lock LOCK]  the N largest peaks (default 15)

A --lean-processes workload (scripts/full-build.sh, docs/build-budgets.md#elastic-workloads) runs
every Lean elaboration as its own sub-admission of build-guard, charged 1.3 x the module's
measured peak and stopped and run again at the declared bound (build-guard PROCESS_MIB, 11000
MiB) when it outgrows that. A measurement belongs to one source text: the module's path in the
workspace and the SHA-256 of its file. A module whose source changed is charged 1.3 x the peak
of its earlier source until it ran once more (a guess: the retry at the declared bound covers a
module that grew), one never measured the declared bound. (A change in its imports keeps the
measurement, for the same reason.) Charging the declared bound for every changed module made
each one an 11-slot queue head on the shared remote host, with lane jobs waiting beside it.

The measurements come from two places, in this order:
- this machine's store, `<lock>.d/lean-peaks.json` beside build-guard's lock: each successful
  elaboration's exact peak (the kernel's high-water mark of the Lean process, at one Lean thread),
  the last RUNS of each source text;
- the committed table assurance/lean-peaks.json: generated by `write` from the store and the table
  before it (an entry stays until its module is measured again: with the sha256 of an earlier
  source it is the prior of a changed module), never edited by hand. It seeds a
  machine that has not measured a module yet (a fresh build host, a cleared cache).
"""

from __future__ import annotations

import fcntl
import hashlib
import json
import math
import os
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
TABLE = Path('assurance/lean-peaks.json')
RUNS = 3
NOTE = ('Generated by `python3 -B scripts/lean-peaks.py write` from the measured peaks of this '
        "machine's builds (build-guard --lean-processes, docs/build-budgets.md#elastic-workloads); "
        'never edit it by hand. peak_mib is the largest measured peak of the elaboration of the '
        'module whose source has this sha256; a module whose source changed since is charged 1.3 x '
        'this peak as a guess (a retry at the declared bound if it outgrows it) until it is measured '
        'again.')


def _entry(entry):
    """A well-formed store entry, else None (the store is a cache: a bad entry is unmeasured)."""
    number = lambda x: isinstance(x, int) and not isinstance(x, bool) and x > 0
    if isinstance(entry, dict) and isinstance(entry.get('sha256'), str) \
            and isinstance(entry.get('peaks_kib'), list) and entry['peaks_kib'] \
            and all(map(number, entry['peaks_kib'])):
        return entry
    return None


def _read(handle) -> dict:
    try:
        data = json.loads(handle.read() or '{}')
    except ValueError:
        return {}
    return {k: v for k, v in data.items() if _entry(v)} if isinstance(data, dict) else {}


def read_store(store: Path) -> dict:
    """The store's entries. It is replaced whole (`record`), so a reader needs no lock."""
    try:
        with store.open() as handle:
            return _read(handle)
    except FileNotFoundError:
        return {}


def read_table(workspace: Path) -> dict:
    """{module: {'peak_mib', 'sha256'}} of the committed table (none when absent or malformed)."""
    try:
        data = json.loads((workspace / TABLE).read_text())
    except (OSError, ValueError):
        return {}
    modules = data.get('modules') if isinstance(data, dict) else None
    if not isinstance(modules, dict):
        return {}
    return {k: v for k, v in modules.items() if isinstance(v, dict) and isinstance(v.get('sha256'), str)
            and isinstance(v.get('peak_mib'), int) and v['peak_mib'] > 0}


def known_peak_kib(store: Path, workspace: Path, module: str, sha: str | None) -> int | None:
    """The measured peak of `module` with source `sha` (KiB), or None: unmeasured or stale."""
    if sha is None:
        return None
    entry = read_store(store).get(module)
    if entry and entry['sha256'] == sha:
        return max(entry['peaks_kib'])
    row = read_table(workspace).get(module)
    if row and row['sha256'] == sha:
        return row['peak_mib'] * 1024
    return None


def prior_peak_kib(store: Path, workspace: Path, module: str) -> int | None:
    """The measured peak of an earlier source of `module` (KiB): this machine's, else the
    committed row's; None for a module never measured. A guess for its changed source, safe
    because the charge is the process's limit: a module that grew costs one retry."""
    entry = read_store(store).get(module)
    if entry:
        return max(entry['peaks_kib'])
    row = read_table(workspace).get(module)
    return row['peak_mib'] * 1024 if row else None


def record(store: Path, module: str, sha: str, peak_kib: int) -> None:
    """Add one successful elaboration's peak to the store (the last RUNS of this source)."""
    if not isinstance(peak_kib, int) or peak_kib <= 0:
        return
    store.parent.mkdir(parents=True, exist_ok=True)
    # Writers take turns on a lock file beside the store and replace it whole: a stopped writer
    # leaves the old store, never a torn one.
    with open(str(store) + '.lock', 'a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        data = read_store(store)
        old = data.get(module)
        peaks = old['peaks_kib'] if old and old['sha256'] == sha else []
        data[module] = {'sha256': sha, 'peaks_kib': ([peak_kib] + peaks)[:RUNS]}
        with tempfile.NamedTemporaryFile('w', dir=store.parent, prefix='.lean-peaks-',
                                         delete=False) as handle:
            json.dump(data, handle, sort_keys=True)
        os.replace(handle.name, store)


def store_of(lock: Path) -> Path:
    """The store beside build-guard's lock (resolved, as the guard resolves its --lock)."""
    return Path(str(Path(lock).expanduser().resolve()) + '.d') / 'lean-peaks.json'


def default_store() -> Path:
    return store_of(Path(os.environ.get('AIR2LEAN_BUILD_LOCK',
                                        str(Path.home() / '.cache/air2lean/build.lock'))))


def sources(workspace: Path) -> dict:
    """{module: sha256} of the workspace's tracked .lean files."""
    names = subprocess.run(['git', 'ls-files', '-z', '--', '*.lean'], cwd=workspace, check=True,
                           capture_output=True, text=True).stdout.split('\0')
    found = {}
    for name in filter(None, names):
        try:
            found[name] = hashlib.sha256((workspace / name).read_bytes()).hexdigest()
        except FileNotFoundError:
            pass  # deleted in the worktree
    return found


def table(store: Path, workspace: Path) -> dict:
    """The regenerated table: for each tracked module, this machine's measurement of its
    current source, else the committed one if its source is unchanged, else the latest
    measurement of an earlier source (with that source's sha256: the prior `prior_peak_kib`
    guesses from until the module is measured again)."""
    measured, committed = read_store(store), read_table(workspace)
    modules = {}
    for module, sha in sorted(sources(workspace).items()):
        entry, row = measured.get(module), committed.get(module)
        if entry and entry['sha256'] == sha:
            modules[module] = {'peak_mib': math.ceil(max(entry['peaks_kib']) / 1024), 'sha256': sha}
        elif row and row['sha256'] == sha:
            modules[module] = {'peak_mib': row['peak_mib'], 'sha256': sha}
        elif entry:
            modules[module] = {'peak_mib': math.ceil(max(entry['peaks_kib']) / 1024), 'sha256': entry['sha256']}
        elif row:
            modules[module] = {'peak_mib': row['peak_mib'], 'sha256': row['sha256']}
    return {'schema': 1, 'note': NOTE, 'modules': modules}


def main(argv: list[str]) -> int:
    args = list(argv)
    store = default_store()
    if '--lock' in args:
        i = args.index('--lock')
        store = store_of(Path(args[i + 1]))
        del args[i:i + 2]
    if args[:1] == ['write'] and len(args) == 1:
        data = table(store, ROOT)
        (ROOT / TABLE).write_text(json.dumps(data, indent=1, sort_keys=True) + '\n')
        print('lean-peaks: %d modules measured (%s)' % (len(data['modules']), TABLE))
        return 0
    if args[:1] == ['top'] and len(args) <= 2:
        count = int(args[1]) if len(args) == 2 else 15
        rows = sorted(table(store, ROOT)['modules'].items(), key=lambda item: -item[1]['peak_mib'])
        for module, row in rows[:count]:
            print('%7d MiB  %s' % (row['peak_mib'], module))
        return 0
    print(__doc__.split('\n\n')[1], file=sys.stderr)
    return 2


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
