"""Check fresh canonicalization certificates from gen-integrity's actual translations.

There is no case inventory or success cache here. gen-integrity supplies every case and
its Translator; each invocation compiles the actual snapshots and runs fresh Assurance
kernel replay for the complete batch. Run under the caller's standard build guard.
"""
import hashlib
from itertools import islice
import json
import os
from pathlib import Path
import re
import subprocess
import time

ROOT = Path(__file__).resolve().parent.parent
BATCH_SIZE = 8
CERTIFICATE_HEADER = (
    "import Air2Lean.CanonCertificate\n\n"
    "-- Generated by air2lean --canon-certificate; scripts/gen-integrity.py owns freshness.\n"
    "-- Only debug definition IDs are certified, relative to Air2Lean.Sem.\n")


def lean_string(value):
    """Quote using Lean's escapes, including Unicode escapes for every control character."""
    escapes = {'"': '\\"', '\\': '\\\\', '\n': '\\n', '\r': '\\r', '\t': '\\t'}
    return '"' + "".join(escapes.get(char, f"\\u{ord(char):04x}" if ord(char) < 32 else char)
                         for char in value) + '"'


def lean(path, compile_module=False):
    output = [f"--root={path.parent}", "-o", str(path.with_suffix(".olean"))] if compile_module else []
    return subprocess.run(["lake", "env", "lean", *output, str(path)], cwd=ROOT,
                          capture_output=True, text=True, timeout=900)


def roundtrip_source(source, translator, index):
    """Scope the known emitter's body; imports belong once at the batch's file top."""
    namespaces = re.findall(r"^namespace (.+)$", source, re.M)
    if (not source.startswith(CERTIFICATE_HEADER) or len(namespaces) != 1
            or re.findall(r"^import (.+)$", source, re.M) != ["Air2Lean.CanonCertificate"]
            or not source.rstrip().endswith(f"\nend {namespaces[0]}")):
        raise ValueError("canonicalization certificate has an unexpected emitter header or namespace")
    namespace, = namespaces
    arguments = ", ".join(lean_string(a) for a in translator.arguments[index])
    directory = lean_string(translator.arguments[index][0])
    body = source.removeprefix("import Air2Lean.CanonCertificate\n")
    wrapper = (f"namespace CanonCase{index}\n" + body + "\n#eval do\n"
               f"  let args ← IO.ofExcept (Air2Lean.parseArgs [{arguments}])\n"
               f"  let changed ← Air2Lean.CanonCertificate.checkDirectory {directory} args.allocatorModel "
               f"{namespace}.snapshots\n"
               f'  IO.println s!"canon-snapshot-count:{index}:{{{namespace}.snapshots.size}}"\n'
               f'  IO.println s!"canon-debug-changes:{index}:{{changed}}"\n'
               f"end CanonCase{index}\n")
    return f"CanonCase{index}.{namespace}", wrapper


def native_results(stdout, indices):
    """Require exactly one native count and change result for every case in this batch."""
    results = []
    for label, value in (("snapshot-count", r"\d+"), ("debug-changes", "true|false")):
        rows = re.findall(rf"^canon-{label}:([^\n]*)$", stdout, re.M)
        parsed = [re.fullmatch(rf"(\d+):({value})", row) for row in rows]
        if (any(row is None for row in parsed) or len(parsed) != len(indices)
                or {int(row[1]) for row in parsed if row} != set(indices)):
            raise ValueError("missing or duplicate indexed native snapshot binding result\n" + stdout)
        results.append({int(row[1]): row[2] for row in parsed})
    return results


def batch_source(batch, translator):
    if not 1 <= len(batch) <= BATCH_SIZE or len({index for index, _, _ in batch}) != len(batch):
        raise ValueError("canonicalization batch must contain at most eight distinct cases")
    records, wrappers = [], []
    for index, case, source in batch:
        namespace, wrapper = roundtrip_source(source, translator, index)
        definitions = re.findall(r"^def (\w+) :", source, re.M)
        if definitions.count("snapshots") != 1 or len(definitions) != len(set(definitions)):
            raise ValueError(f"{case.label}: invalid generated canonicalization declaration inventory")
        # snapshots is the native-binding aggregate; every other emitted data declaration
        # must be reached from this case's actual per-function theorem roots in Assurance.
        records.append(dict(index=index, namespace=namespace, bytes=len(source.encode()),
                            helpers=[f"{namespace}.{name}" for name in definitions if name != "snapshots"]))
        wrappers.append(wrapper)
    # Real emitter namespaces start with Air2Lean. Their outer case namespace
    # must not hide the global AIR declarations from the emitted unqualified terms.
    header = "import Air2Lean.Main\nimport Air2Lean.CanonCertificate\n\nopen _root_.Air2Lean\n\n"
    return records, header + "\n".join(wrappers)


def compile_batch(batch, translator, batch_index):
    records, source = batch_source(batch, translator)
    path = translator.work / f"RoundTripBatch{batch_index}.lean"
    path.write_text(source)
    start = time.monotonic()
    result = lean(path, compile_module=True)
    if result.returncode != 0:
        raise ValueError(f"{path.stem}: canonicalization certificate batch failed\n"
                         + result.stdout + result.stderr)
    counts, changes = native_results(result.stdout, [record["index"] for record in records])
    olean = path.with_suffix(".olean")
    with olean.open("rb") as stream:
        digest = hashlib.file_digest(stream, "sha256").hexdigest()
    elapsed = time.monotonic() - start
    for record in records:
        record.update(module=path.stem, count=int(counts[record["index"]]),
                      changed=changes[record["index"]] == "true",
                      olean=str(olean.resolve()), olean_sha256=digest)
    print(f"canonicalization {path.stem}: {len(records)} cases, kernel proofs and both native snapshots check "
          f"({sum(record['bytes'] for record in records)} certificate bytes; {elapsed:.3f}s)", flush=True)
    return records


def reject_mutant(batch, translator):
    """One changed live definition ID must reject the entire otherwise unchanged batch."""
    live = "(fun i : Inst => match i.op with | .line _ | .dbg .. => false | _ => true)"
    for position, (index, case, source) in enumerate(batch):
        for target in re.finditer(r"^def before_body_(\d+) : Array Inst :=\n(.*?)\n\ndef after_body_",
                                  source, re.M | re.S):
            after = re.search(rf"^def after_body_{target[1]} : Array Inst :=\n(.*?)\n\ndef after_",
                              source, re.M | re.S)
            if after is None:
                raise ValueError("missing mapped target body in wrong-canonicalization control")
            start, end = after.span(1)
            replacement = (f"  let body := ({after[1].strip()})\n"
                           f"  match body.findIdx? {live} with\n"
                           "  | some index => body.modify index (fun i => { i with id := i.id + 1000000 })\n"
                           "  | none => body\n\n"
                           f'#eval IO.println s!"canon-mutant-live:{index}:{{before_body_{target[1]}.any {live}}}"')
            mutant = source[:start] + replacement + source[end:]
            mutated_batch = list(batch)
            mutated_batch[position] = (index, case, mutant)
            _, assembled = batch_source(mutated_batch, translator)
            _, wrapper = roundtrip_source(mutant, translator, index)
            offset = assembled[:assembled.index(wrapper)].count("\n")
            path = translator.work / "WrongCanonicalization.lean"
            path.write_text(assembled)
            result = lean(path)
            output = result.stdout + result.stderr
            applicable = re.findall(r"^canon-mutant-live:(\d+):(true|false)$", output, re.M)
            if applicable == [(str(index), "false")] and result.returncode == 0:
                continue
            if applicable == [(str(index), "true")] and result.returncode == 0:
                raise ValueError("wrong canonicalization still checks")
            lines = wrapper.splitlines()
            proof = next((offset + i + 1 for i, line in enumerate(lines)
                          if line.startswith(f"theorem erased_{target[1]} :")), None)
            next_proof = next((offset + i + 1 for i, line in enumerate(lines)
                               if line.startswith(f"theorem preserves_{target[1]} ")), None)
            errors = [int(match[1]) for match in re.finditer(
                rf"^{re.escape(str(path))}:(\d+):\d+: error:", output, re.M)]
            if (applicable != [(str(index), "true")] or proof is None or next_proof is None or not errors
                    or not proof <= errors[0] < next_proof):
                raise ValueError("wrong-canonicalization control failed outside its actual equality obligation\n"
                                 + output)
            return True
    return False


def check_audit(report, records):
    """Bind every actual function to its two checked theorem roots, including shared Gen cases."""
    expected_modules = sorted({"Air2Lean.CanonSem", "Air2Lean.CanonCertificate",
                               *(record["module"] for record in records)})
    replay = report.get("kernel_replay", {})
    if (report.get("status") != "pass" or report.get("violations") != []
            or report.get("modules") != expected_modules or replay.get("status") != "pass"
            or replay.get("rejected") != [] or replay.get("reused") != []):
        raise ValueError("canonicalization Assurance audit did not freshly accept its complete scope")
    theorems = report.get("theorems", [])
    if any(not theorem.get("allowed") for theorem in theorems):
        raise ValueError("canonicalization Assurance audit contains a rejected theorem")
    roots = {(theorem["module"], theorem["name"]) for theorem in theorems}
    artifacts = {row["module"]: row for row in report.get("freshness", {}).get("artifacts", [])}
    nodes = {node["name"]: node for node in report.get("nodes", [])}
    for record in records:
        if not record["namespace"].startswith(f"CanonCase{record['index']}."):
            raise ValueError(f"{record['module']}: swapped canonicalization case namespace")
        artifact = artifacts.get(record["module"], {})
        olean = Path(artifact.get("olean", ""))
        if not olean.is_absolute():
            olean = ROOT / olean
        if (olean.resolve() != Path(record["olean"]).resolve()
                or artifact.get("olean_sha256") != record["olean_sha256"]):
            raise ValueError(f"{record['module']}: replay did not bind the freshly compiled certificate artifact")
        expected = {(record["module"], f"{record['namespace']}.{kind}_{index}")
                    for index in range(record["count"]) for kind in ("erased", "preserves")}
        missing = expected - roots
        if missing:
            raise ValueError(f"{record['module']}: missing per-function canonicalization proofs: "
                             + ", ".join(name for _, name in sorted(missing)))
        expected_names = {name for _, name in expected}
        pending = list(expected_names)
        reached = set()
        while pending:
            name = pending.pop()
            if name in reached:
                continue
            reached.add(name)
            # Imported modules cannot depend on declarations in this fresh module.
            pending.extend(dependency for dependency in nodes.get(name, {}).get("dependencies", [])
                           if nodes.get(dependency, {}).get("module") == record["module"])
        required = set(record["helpers"]) | expected_names
        uncovered = [name for name in required if name not in reached
                     or nodes.get(name, {}).get("module") != record["module"]]
        if uncovered:
            raise ValueError(f"{record['module']}: uncovered canonicalization declarations: "
                             + ", ".join(sorted(uncovered)))


def audit_certificates(work, records):
    environment = dict(os.environ)
    environment["LEAN_PATH"] = str(work) + (os.pathsep + environment["LEAN_PATH"]
                                             if environment.get("LEAN_PATH") else "")
    environment["AIR2LEAN_REPLAY_JOBS"] = environment.get("AIR2LEAN_JOBS", "1")
    modules = sorted({"Air2Lean.CanonSem", "Air2Lean.CanonCertificate",
                      *(record["module"] for record in records)})
    path = work / "audit.json"
    arguments = [str(ROOT / "scripts/assumptions.sh"), "--no-build", "--output", str(path)]
    for module in modules:
        arguments += ["--module", module]
    start = time.monotonic()
    # No --replay-cache: every selected artifact and non-toolchain dependency is replayed now.
    result = subprocess.run(arguments, cwd=ROOT, env=environment, capture_output=True,
                            text=True, timeout=7200)
    if result.returncode != 0:
        raise ValueError("canonicalization Assurance audit failed\n" + result.stdout + result.stderr)
    check_audit(json.loads(path.read_text()), records)
    for record in {record["module"]: record for record in records}.values():
        with Path(record["olean"]).open("rb") as stream:
            digest = hashlib.file_digest(stream, "sha256").hexdigest()
        if digest != record["olean_sha256"]:
            raise ValueError(f"{record['module']}: compiled certificate changed during its audit")
    print(f"canonicalization: fresh Assurance audit/replay {time.monotonic() - start:.3f}s", flush=True)


def certify(translator, indexed_cases):
    records = []
    mutated = False
    cases = iter(indexed_cases)
    batch_index = 0
    while batch_cases := list(islice(cases, BATCH_SIZE)):
        batch = []
        for index, case in batch_cases:
            difference = translator.matches(index, case, case.path)
            if difference is not None:
                raise ValueError(f"{case.label}: generated module changed ({difference})")
            batch.append((index, case, translator.certificate(index, case).decode()))
        records.extend(compile_batch(batch, translator, batch_index))
        if not mutated:
            mutated = reject_mutant(batch, translator)
        del batch
        batch_index += 1
    if not records:
        raise ValueError("no translation cases selected for canonicalization certification")
    if not mutated:
        raise ValueError("selected cases did not exercise the wrong-canonicalization control")
    if not any(record["changed"] for record in records):
        raise ValueError("selected cases did not change any actual debug definition ID")
    audit_certificates(translator.work, records)
    print(f"canonicalization: {len(records)} cases, {sum(r['count'] for r in records)} functions, "
          f"{sum(r['bytes'] for r in records)} certificate bytes checked; "
          "wrong canonicalization rejected", flush=True)
